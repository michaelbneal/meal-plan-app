// Writes android/app/src/main/res/xml/network_security_config.xml before `cap sync android`.
//
// Android blocks plain http:// by default (like iOS App Transport Security). Rather than
// switch cleartext on for every host, allow it only where the LAN container can live:
// localhost, the emulator's host alias 10.0.2.2, and the host named in VITE_API_URL when
// that URL is http://. HTTPS hosts (the App Runner backend) need nothing. This is the
// Android counterpart of NSAllowsLocalNetworking in ios/App/App/Info.plist.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const frontendDir = dirname(dirname(fileURLToPath(import.meta.url)));
const hosts = new Set(['localhost', '10.0.2.2']);

// Same precedence Vite uses for `--mode native`: .env.native, then .env.native.local.
let apiUrl = process.env.VITE_API_URL || '';
for (const name of ['.env.native', '.env.native.local']) {
  const file = join(frontendDir, name);
  if (!existsSync(file)) continue;
  for (const line of readFileSync(file, 'utf8').split('\n')) {
    const m = line.match(/^\s*VITE_API_URL\s*=\s*(.+?)\s*$/);
    if (m) apiUrl = m[1].replace(/^(['"])(.*)\1$/, '$2');
  }
}
if (apiUrl) {
  try {
    const url = new URL(apiUrl);
    if (url.protocol === 'http:') hosts.add(url.hostname);
  } catch {
    console.warn(`android-network-config: VITE_API_URL is not a valid URL: ${apiUrl}`);
  }
}

const xml = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/android-network-config.mjs (npm run android:sync). Do not edit by hand. -->
<network-security-config>
    <base-config cleartextTrafficPermitted="false" />
    <domain-config cleartextTrafficPermitted="true">
${[...hosts].map((h) => `        <domain includeSubdomains="false">${h}</domain>`).join('\n')}
    </domain-config>
</network-security-config>
`;

const out = join(frontendDir, 'android', 'app', 'src', 'main', 'res', 'xml', 'network_security_config.xml');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, xml);
console.log(`android-network-config: cleartext allowed for ${[...hosts].join(', ')}`);
